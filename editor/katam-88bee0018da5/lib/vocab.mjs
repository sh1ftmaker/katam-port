// The authoring vocabulary: enum names the schemas and files use, derived from
// committed C sources only (no ROM bytes):
//
//   objectTypes   game/include/constants/object_types.h   OBJ_WADDLE_DEE_1 -> "waddle_dee_1"
//   songs         game/include/constants/songs.h          MUS_RAINBOW_ROUTE -> "mus_rainbow_route"
//   abilities     game/include/constants/kirby.h          KIRBY_ABILITY_FIRE -> "fire"
//   areas         game/include/pause_area_map.h           AREA_RAINBOW_ROUTE -> "rainbow_route"
//   roomAreas     game/src/pause_area_map.c               sAreaMapRoomInfos: room id -> area
//   collision     game/src/code_080023A4.c                gCollisionAttributes[256] words
//
// `buildVocab(readText)` returns the object; tools/katam writes it to
// assets/schema/authoring/vocab.json so the browser editor needs no C parsing.

const snake = (s) => s.toLowerCase();

function defines(text, prefix) {
  const out = [];
  for (const m of text.matchAll(new RegExp(`#define\\s+${prefix}(\\w+)\\s+(0x[0-9A-Fa-f]+|\\d+)\\b`, 'g'))) {
    out.push([m[1], Number(m[2])]);
  }
  return out;
}

/** Bit-derived description of a metatile attribute word (docs/naming/metatile-attributes.md).
 *  Mechanical, so it never needs renaming; the semantics registry layers names on top. */
export const ATTR_FLAGS = [
  [0x1, 'empty'], [0x2, 'water'], [0x4, 'top_solid'], [0x8, 'drop_through'], [0x10, 'slippery'],
  [0x20, 'chain_trigger'], [0x40, 'chain_member'], [0x80, 'flag80'], [0x100, 'ladder'], [0x200, 'solid'],
  [0x400, 'mini_only'], [0x800, 'force'], [0x1000, 'breakable'], [0x2000, 'hazard'], [0x4000, 'door'],
  [0x8000, 'flag8000'],
];

export function describeAttr(word) {
  if (word === 0) return 'unused';
  const parts = ATTR_FLAGS.filter(([m]) => word & m).map(([, n]) => n);
  const slope = word >>> 28, dir = (word >>> 24) & 0xf, lvl = (word >>> 20) & 0xf;
  if (slope) parts.push(`slope${slope}`);
  if (dir) parts.push(`dir${dir}`);
  if (lvl) parts.push(`lvl${lvl}`);
  return parts.join('+');
}

export function buildVocab(readText) {
  const objH = readText('game/include/constants/object_types.h');
  const objectTypes = {};
  for (const [n, v] of defines(objH, 'OBJ_')) if (v < 0x100 && !(snake(n) in objectTypes)) objectTypes[snake(n)] = v;

  const songs = {};
  const songH = readText('game/include/constants/songs.h');
  for (const [n, v] of defines(songH, '')) if (/^(MUS|SE)_/.test(n)) songs[snake(n)] = v;

  const abilities = {};
  for (const [n, v] of defines(readText('game/include/constants/kirby.h'), 'KIRBY_ABILITY_')) {
    if (n !== 'COUNT' && !n.startsWith('CHANGE_')) abilities[snake(n)] = v;
  }

  const areaH = readText('game/include/pause_area_map.h');
  const enumBody = areaH.match(/enum AreaId\s*\{([^}]*)\}/)[1];
  const areas = {};
  enumBody.split(',').map((s) => s.trim()).filter((s) => s.startsWith('AREA_')).forEach((s, i) => { areas[snake(s.slice(5))] = i; });

  const roomAreas = {};
  const amap = readText('game/src/pause_area_map.c');
  for (const m of amap.matchAll(/\.roomId\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*\.areaId\s*=\s*AREA_(\w+)/g)) {
    const id = Number(m[1]);
    if (!(id in roomAreas)) roomAreas[id] = snake(m[2]);
  }

  const code = readText('game/src/code_080023A4.c');
  const body = code.match(/gCollisionAttributes\[\]\s*=\s*\{([^}]*)\}/)[1];
  const words = [...body.matchAll(/0x[0-9A-Fa-f]+|\d+/g)].map((m) => Number(m[0]) >>> 0);
  if (words.length !== 256) throw new Error(`gCollisionAttributes: expected 256 words, found ${words.length}`);
  const collision = words.map((w, i) => ({ value: i, word: '0x' + w.toString(16).toUpperCase().padStart(8, '0'), bits: describeAttr(w) }));

  return {
    format: 'katam-vocab/1',
    note: 'Generated by `tools/katam/katam.mjs vocab` from committed C headers. No ROM data.',
    objectTypes, songs, abilities, areas, roomAreas, collision,
  };
}

/** Reverse lookups, built once per vocab. */
export function indexVocab(v) {
  const rev = (o) => Object.fromEntries(Object.entries(o).map(([k, n]) => [n, k]));
  return { ...v, objectTypeName: rev(v.objectTypes), songName: rev(v.songs), abilityName: rev(v.abilities) };
}
