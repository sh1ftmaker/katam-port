#!/usr/bin/env python3
"""make_recordings.py -- write the scripted input recordings in tests/recordings/.

The recordings are inputs only (platform/port/inputlog.h has the format): key
masks by frame, and warp requests by room number and cell.  They are produced
by this script rather than captured from a person, so that they can be
regenerated and read.  Nothing in them comes from the ROM; the warp cells were
picked once with tools/room_export.py --spawn (which does read the ROM, at
generation time only) and are written out as plain numbers below.

    python3 tools/make_recordings.py [--out tests/recordings]

Regenerating a recording invalidates its golden hash log -- run
tests/regress.sh --update afterwards, and say why in the commit.

The scenarios:

  boot_to_level   power-on, logo, title, file select (new file), the intro
                  room.  Tap A+Right on a 20-frame period from frame 120 --
                  the pattern tools/native_smoke.sh has always used.
  attract         no input at all for 9000 frames: the title screen times out
                  into the game's own attract-mode demo, which is the game
                  playing itself through a level with its own recorded input.
  play_rooms      boot to the first level, then a warp into each of a run of
                  level rooms and ~600 frames of play in each: Kirby floats
                  right, presses Up for doors, exhales, swallows.
  warp_sweep      boot to the first level, then a warp every 160 frames
                  through a spread of 36 rooms across every area.
  aim             boot, then 600 hands-off frames in each room that holds an
                  enemy aiming with the BIOS's ArcTan2 (Shotzo, Bang-Bang)
                  and the two bosses whose code drew RNG in argument lists
                  (Kracko, Gobbler) -- the code the determinism work changed --
                  and Mega Titan's room, which faulted the LP64 build.
  wide_view       play_rooms' rooms and play, plus Kracko's arena (a scroll
                  lock), with the session view (`view` lines: the spawn and
                  despawn windows, platform/view.c) at 0.5x zoom 21:9
                  (746x320) from frame 1, narrowed to 400x224 and then to the
                  original 240x160 mid-run, and widened back.
  tutorial_walk   boot a fresh save into the tutorial room (803), then float
                  right across it and back left, with the session view at
                  0.5x zoom 21:9 (744x320) from frame 1: the camera crosses
                  the room both ways and stops at both ends, which is where
                  the zoomed-out parallax used to flicker (docs/RENDERER.md,
                  "Parallax at any zoom").
"""
import argparse
from pathlib import Path

A, B, SELECT, START, RIGHT, LEFT, UP, DOWN, R, L = (1 << i for i in range(10))

# (room, cellX, cellY) -- door-arrival cells from room_export.py --spawn.
PLAY_ROOMS = [(101, 3, 7), (104, 2, 9), (106, 2, 9), (202, 3, 4), (205, 3, 3),
              (310, 4, 9), (402, 4, 4), (502, 2, 7), (601, 4, 9), (704, 2, 8)]


def boot(keys, upto=1300):
    for f in range(upto):
        keys[f] = (A | RIGHT) if f >= 120 and (f - 120) % 20 < 10 else 0


def play(keys, start, end):
    """Float right, tap Up for doors, exhale every so often, inhale too."""
    for f in range(start, end):
        p = (f - start) % 40
        m = RIGHT
        if p < 4:
            m = UP
        elif 10 <= p < 24:
            m |= A
        if (f - start) % 200 in range(150, 156):
            m = B
        keys[f] = m


def walk(keys, start, end, turn):
    """Walk right, floating over the clouds, and from `turn` back left."""
    for f in range(start, end):
        p = (f - start) % 120
        m = RIGHT if f < turn else LEFT
        if p < 70 and p % 10 < 5:
            m |= A
        keys[f] = m


def write(path, frames, keys, warps=(), comment='', views=()):
    with open(path, 'w') as o:
        o.write('katam-input 1\n')
        o.write('# %s\n' % comment)
        o.write('# generated by tools/make_recordings.py; inputs only, no game data\n')
        o.write('frames %d\n' % frames)
        events = [(f, 'view %d %d %d' % (f, w, h)) for f, w, h in views]
        events += [(f, 'warp %d 0 %d %d %d' % (f, r, x, y)) for f, r, x, y in warps]
        prev = None
        for f in range(frames):
            for ef, line in events:
                if ef == f:
                    o.write(line + '\n')
            k = keys.get(f, 0)
            if k != prev:
                o.write('k %d %03X\n' % (f, k))
                prev = k
        o.write('end\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(Path(__file__).resolve().parent.parent
                                         / 'tests' / 'recordings'))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    keys = {}
    boot(keys, 1400)
    write(out / 'boot_to_level.txt', 1400, keys,
          comment='power-on -> title -> file select -> the first level')

    write(out / 'attract.txt', 9000, {},
          comment='no input: title screen, then the attract-mode demo')

    keys = {}
    boot(keys)
    warps = []
    f = 1300
    for room, x, y in PLAY_ROOMS:
        warps.append((f, room, x, y))
        play(keys, f, f + 600)
        f += 600
    write(out / 'play_rooms.txt', f, keys, warps,
          comment='boot, then play through a run of level rooms')

    keys = {}
    boot(keys)
    warps = []
    f = 1300
    for room, x, y in SWEEP:
        warps.append((f, room, x, y))
        # Hands off: Kirby lands and stands.  Walking about in 36 rooms picked
        # up the bomb ability on the way, and the bomb's effect sprite then
        # traps the wasm build in sub_0815521C (docs/DETERMINISM.md).
        f += 160
    write(out / 'warp_sweep.txt', f, keys, warps,
          comment='boot, then a warp every 160 frames through a spread of 36 rooms')

    keys = {}
    boot(keys)
    warps = []
    f = 1300
    for room, x, y in AIM:
        warps.append((f, room, x, y))
        f += 600
    write(out / 'aim.txt', f, keys, warps,
          comment='boot, then stand in rooms with ArcTan2 aimers and RNG bosses')

    keys = {}
    boot(keys)
    warps = []
    f = 1300
    for room, x, y in PLAY_ROOMS + [(324, 4, 19)]:
        warps.append((f, room, x, y))
        play(keys, f, f + 600)
        f += 600
    views = [(1, 746, 320),                 # 0.5x zoom, 21:9
             (1300 + 3 * 600 + 300, 400, 224),
             (1300 + 5 * 600 + 300, 240, 160),
             (1300 + 7 * 600 + 100, 746, 320)]
    write(out / 'wide_view.txt', f, keys, warps, views=views,
          comment='play_rooms with the spawn window sized for a wide view, '
                  'changed mid-run')

    keys = {}
    boot(keys, 420)
    walk(keys, 420, 1900, 1150)
    write(out / 'tutorial_walk.txt', 1900, keys, views=[(1, 744, 320)],
          comment='boot into the tutorial room, float right across it and back')


# A spread of rooms over every area: every eighth room that has an arrival
# cell, from room_export.py --spawn (738, Mega Titan, is in aim instead).
# This was cut to every tenth room at 150 frames while the 36-room sweep
# trapped the wasm build at frame 5781 in sub_080788AC -> sub_08155128
# (gUnk_083507F8 read past its end, kirby.c); fixed, so it is the full sweep.
SWEEP = [
    (101, 3, 7), (113, 89, 7), (122, 4, 3), (134, 2, 7), (142, 5, 19),
    (170, 3, 9), (178, 90, 9), (195, 3, 9), (209, 11, 3), (218, 15, 3),
    (226, 12, 8), (291, 9, 3), (316, 60, 4), (326, 1, 2), (406, 7, 8),
    (415, 77, 1), (423, 3, 9), (502, 2, 7), (512, 4, 7), (525, 2, 19),
    (533, 39, 17), (541, 5, 5), (553, 3, 4), (591, 9, 3), (608, 72, 4),
    (617, 4, 9), (700, 3, 9), (710, 5, 5), (730, 29, 4), (739, 4, 4),
    (800, 10, 4), (814, 3, 3), (825, 18, 19), (890, 9, 3), (916, 0, 8),
    (970, 15, 6),
]

# Rooms holding the enemies whose code changed in the determinism work, from
# room_export.py's object lists and --spawn arrival cells: Shotzo (225, 113,
# 203), Bang-Bang (325, 103, 118), Kracko (324), Gobbler (822); and Mega
# Titan (738), whose arm setup faulted the LP64 build.
AIM = [
    (225, 13, 7), (113, 89, 7), (203, 59, 5), (325, 4, 20), (103, 2, 39),
    (118, 3, 5), (324, 4, 19), (822, 12, 3),
    (738, 14, 7),   # Mega Titan: its arm setup read through NULL (mega_titan.c)
]

if __name__ == '__main__':
    main()
