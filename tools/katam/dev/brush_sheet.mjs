import fs from 'node:fs'; import path from 'node:path'; import zlib from 'node:zlib';
const P = '/bigdata/agent-tom/projects/katamport/port/tools/katam/lib/';
const imp = (n) => import(P + n + '.mjs');
const [{ nodeIO }, png, { indexVocab }, { loadRegistry }, project, grid, tiles, gfx, auto] = await Promise.all(['io','png','vocab','registry','project','grid','tiles','gfx','autotile'].map(imp));
png.setZlib({ deflate: (b) => new Uint8Array(zlib.deflateSync(b)), inflate: (b) => new Uint8Array(zlib.inflateSync(b)) });
const ROOT = '/bigdata/agent-tom/projects/katamport/port/';
const io = await nodeIO();
const vocab = indexVocab(JSON.parse(fs.readFileSync(ROOT + 'assets/schema/authoring/vocab.json', 'utf8')));
const registry = loadRegistry(io, ROOT + 'assets/schema/semantics');
const vp = process.env.CLAUDE_JOB_DIR + '/tmp/van';
const van = project.loadProject(io, vp);
const bind = new project.Bindings(vocab, [van]);
const ctx = project.makeContext({ vocab, registry, bindings: bind });
const TS = process.argv[2] || 'tileset:vanilla/29';
const colClass = ctx.vocab.collision.map((c) => auto.classOfBits(c.bits));
const rooms = []; let first = null;
for (const [id, d] of van.docs) {
  const doc = d.doc; if (!id.startsWith('room:') || doc.tileset !== TS) continue;
  const W = doc.size.width, H = doc.size.height;
  const art = grid.decodeGrid(doc.art, W, H).map((s) => tiles.metaToken(tiles.metaValues(s)));
  const col = grid.decodeGrid(doc.collision, W, H).map((v) => ctx.collisionValue(v));
  rooms.push({ W, H, art, cls: col.map((v) => colClass[v]), col, id }); first = first || doc;
}
const docOf = (id) => { const r = bind.resolve(id); return r ? bind.docs.get(r) : null; };
const ts = docOf(first.tileset), pal = docOf(first.palette);
const rgb5 = (hex) => { const c = gfx.bgr555(hex); return [c & 31, (c >> 5) & 31, (c >> 10) & 31].map((v) => (v << 3) | (v >> 2)); };
const T = gfx.pngToTiles(io.readBytes(`${ts.base}/${ts.doc.image}`), ts.doc.tileCount, ts.doc.image);
const banks = pal.doc.banks.map((b) => b.map(rgb5));
const piece = (tok) => { const im = new Uint8Array(1024); const vals = tiles.metaValues(tok);
  for (let q = 0; q < 4; q++) { const ox = (q & 1) * 8, oy = (q >> 1) * 8, v = vals[q], t = v & 0x3ff, hf = v & 0x400, vf = v & 0x800, bk = banks[v >> 12];
    for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) { const sx = hf ? 7 - x : x, sy = vf ? 7 - y : y, by = T[t * 32 + sy * 4 + (sx >> 1)], ci = sx & 1 ? by >> 4 : by & 15; const o = ((oy + y) * 16 + ox + x) * 4;
      if (!ci) { im[o] = 255; im[o + 1] = 0; im[o + 2] = 255; im[o + 3] = 255; continue; } const c = (bk && bk[ci]) || [16, 14, 30]; im[o] = c[0]; im[o + 1] = c[1]; im[o + 2] = c[2]; im[o + 3] = 255; } } return im; };
const counts = new Map(); for (const R of rooms) R.art.forEach((t) => counts.set(t, (counts.get(t) || 0) + 1));
const empty = [...counts].filter(([t]) => rooms.some((R) => R.art.some((a, i) => a === t && R.cls[i] === 'air'))).sort((a, b) => b[1] - a[1])[0][0];
const model = auto.learn(rooms, empty, { pixels: piece, rules: JSON.parse(fs.readFileSync(ROOT + 'assets/schema/authoring/autotile/tileset-vanilla-29.json','utf8')) });
export { model, rooms, piece, png, counts };
const out = [];
for (const [kind, K] of Object.entries(model.kinds)) for (const s of K.styles) out.push({ kind, id: s.id, name: s.name, cells: s.cells.length, tokens: [...s.tokens].map((t) => [t, counts.get(t)]).sort((a, b) => b[1] - a[1]) });
fs.writeFileSync(process.env.CLAUDE_JOB_DIR + '/tmp/cl/styles.json', JSON.stringify({ rooms: rooms.map((r) => r.id), styles: out }));
console.log(rooms.length, 'rooms;', out.map((o) => `${o.id} cells=${o.cells} pieces=${o.tokens.length}`).join(' | '));
