#!/usr/bin/env python3
"""make_rooms_recordings.py -- scenarios for local multiplayer's rooms mode
(platform/localmp.c): the players apart for long stretches, meeting again
through doors and through the cell phone, pausing apart, a boss room and the
goal room while the other player is elsewhere.

Inputs only (key masks per frame, warps by room and cell, the session view,
`option localmp 2` and `option rooms 1`), like
tools/netaudit/make_localmp_recordings.py, whose grammar and key patterns
this reuses; the rooms and cells are the ones that file and
make_players_recordings.py already use.  Nothing comes from the ROM.

    python3 tools/rooms/make_rooms_recordings.py [--out tests/recordings]

  rooms_apart   two humans from power-on, rooms mode:
                - 1300: player 1 to room 117, player 2 to room 203 (two
                  areas); each plays its own room for ~1100 frames (floating,
                  inhaling, doors 117->118 and back by player 1);
                - 2600: both to 117, player 1 takes the door to 118, player 2
                  takes the same door 200 frames later: a meeting by door;
                - 3000: player 1 to 101, player 2 stays in 118: apart;
                - 3700: player 1 calls on the cell phone (R), player 2
                  answers (R) 40 frames later; at 4100 the reverse;
                - 4600: player 2 pauses while apart, cycles the pages, closes;
                  then player 1 pauses;
                - 5200: player 1 to Kracko's arena (324) and fights hands-on
                  then hands-off; player 2 walks in 104 meanwhile; 6400:
                  player 2 calls, player 1 answers;
                - 7300: player 1 to the goal room (980), rides the star while
                  player 2 is elsewhere; 7700: player 2 to the goal room too.
  rooms_wander  the same boot; the players are apart for 9000 frames, each
                walking and fighting in rooms of its own area, warping every
                900 frames to another room, never meeting except by phone at
                the end (both directions).
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'netaudit'))
from make_localmp_recordings import parse, boot_keys, play_keys, walk_keys  # noqa: E402


def write(path, frames, p1, p2, warps, views=((0, 480, 320),), comments=()):
    def collapse(events):
        d = {}
        for f, m in sorted(events, key=lambda e: e[0]):
            d[f] = m
        out, prev = [], None
        for f in sorted(d):
            if d[f] != prev:
                out.append((f, d[f]))
                prev = d[f]
        return out
    lines = ['katam-input 1']
    lines += ['# ' + c for c in comments]
    lines.append('# no-regress: a scenario for tools/rooms/, not a tests/regress.sh golden')
    lines.append('# generated by tools/rooms/make_rooms_recordings.py; inputs only, no game data')
    lines.append('frames %d' % frames)
    lines += ['option localmp 2', 'option rooms 1']
    for f, w, h in views:
        lines.append('view %d %d %d' % (f, w, h))
    for f, pl, r, x, y in sorted(warps):
        lines.append('warp %d %d %d %d %d' % (f, pl, r, x, y))
    p1 = collapse(p1)
    if not p1 or p1[0][0] != 0:
        p1 = [(0, 0)] + p1
    for f, m in p1:
        lines.append('k %d %03X' % (f, m))
    for f, m in collapse(p2):
        lines.append('kp 1 %d %03X' % (f, m))
    lines.append('end')
    Path(path).write_text('\n'.join(lines) + '\n')


def keys(script, f=0):
    k, _, end = parse(script, f)
    return k, end


def apart(out):
    p1, p2, w = boot_keys(), [], []
    # 1300: two areas
    w += [(1300, 0, 117, 44, 9), (1300, 1, 203, 60, 5)]
    k, _ = keys('@1340 h8:R U U U U @1440 h140:R @1590 h140:L @1750 h30:L U U U U')
    p1 += k + play_keys(1900, 2550)
    p2 += walk_keys(1310, 2550)
    # 2600: a meeting by door: both in 117, player 1 through the door first
    w += [(2600, 0, 117, 44, 9), (2601, 1, 117, 44, 9)]
    k, _ = keys('@2640 h8:R U U U U')
    p1 += k
    k, _ = keys('@2840 h8:R U U U U')
    p2 += k
    p1 += walk_keys(2900, 2990)
    p2 += walk_keys(2900, 2990, delay=7)
    # 3000: apart again
    w += [(3000, 0, 101, 3, 7)]
    p1 += play_keys(3001, 3600)
    p2 += walk_keys(3001, 3600)
    # 3700: the phone, both ways
    k, _ = keys('@3700 r +200')
    p1 += k
    k, _ = keys('@3740 r +200')
    p2 += k
    p1 += walk_keys(3800, 4000)
    p2 += play_keys(3800, 4000)
    w += [(4050, 1, 118, 3, 5)]
    k, _ = keys('@4100 r +200')
    p2 += k
    k, _ = keys('@4140 r +200')
    p1 += k
    p1 += walk_keys(4300, 4550)
    p2 += walk_keys(4300, 4550, delay=11)
    # 4600: pause while apart (player 2 first)
    w += [(4560, 0, 104, 2, 9)]
    k, f = keys('@4600 S +40 s +30 s +30 s +30 S +60')
    p2 += k
    k, f = keys('S +40 s +30 s +30 S +60', f)
    p1 += k
    # 5200: player 1 in Kracko's arena, player 2 walking in another room
    w += [(5200, 0, 324, 4, 19), (5201, 1, 117, 44, 9)]
    p1 += play_keys(5300, 5700)
    p2 += walk_keys(5210, 6300)
    k, _ = keys('@6400 r +200')
    p2 += k
    k, _ = keys('@6440 r +200')
    p1 += k
    # 7300: the goal room, player 2 elsewhere; then player 2 too
    w += [(7300, 0, 980, 7, 70)]
    k, _ = keys('@7340 h20:R h10:L U +40 U +40 A +60')
    p1 += k
    p2 += walk_keys(7300, 7650)
    w += [(7700, 1, 980, 7, 70)]
    k, _ = keys('@7740 h20:R h10:L U +40 U +40 A +60')
    p2 += k
    write(out / 'rooms_apart.txt', 8600, p1, p2, w,
          comments=['rooms mode: players apart, meeting by door and by cell phone, pause apart,',
                    "a boss room and the goal room with the other player elsewhere"])


def wander(out):
    p1, p2, w = boot_keys(), [], []
    a1 = [(117, 44, 9), (101, 3, 7), (104, 2, 9), (118, 3, 5), (324, 4, 19), (117, 44, 9),
          (101, 3, 7), (104, 2, 9), (118, 3, 5), (117, 44, 9)]
    a2 = [(203, 60, 5), (118, 3, 5), (117, 44, 9), (101, 3, 7), (203, 60, 5), (104, 2, 9),
          (118, 3, 5), (203, 60, 5), (101, 3, 7), (104, 2, 9)]
    f = 1300
    for i in range(10):
        r1, r2 = a1[i], a2[i]
        w += [(f, 0) + r1, (f + 1, 1) + r2]
        (play_keys if i % 2 == 0 else walk_keys)
        p1 += (play_keys if i % 2 == 0 else walk_keys)(f + 5, f + 880)
        p2 += (walk_keys if i % 2 == 0 else play_keys)(f + 5, f + 880, delay=3)
        f += 900
    k, _ = keys('@%d r +200' % f)
    p1 += k
    k, _ = keys('@%d r +200' % (f + 40))
    p2 += k
    k, _ = keys('@%d r +200' % (f + 400))
    p2 += k
    k, _ = keys('@%d r +200' % (f + 440))
    p1 += k
    write(out / 'rooms_wander.txt', f + 900, p1, p2, w,
          comments=['rooms mode: two players apart for 9000 frames in rooms of their own,',
                    'meeting by cell phone at the end, both directions'])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(ROOT / 'tests' / 'recordings'))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    apart(out)
    wander(out)


if __name__ == '__main__':
    main()
